import Database from 'better-sqlite3'
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { MIGRATIONS, type Migration } from './legacy.ts'

/**
 * The generator of src/db/schema.ts: the schema the migration chain builds, as one script.
 *
 * A new database runs that script instead of thirty-odd migrations written for databases
 * that no longer exist; an existing one still runs the chain (./legacy.ts). The script is
 * never written by hand: it is read back out of a database the chain built, so the two
 * cannot disagree, and test/db-baseline.test.ts fails when the committed copy is stale.
 *
 *   npm run db:baseline
 */

/** A database built by running `chain` up to and including `through`, the way getDb opens one. */
export function chainDb(chain: readonly Migration[], through: string): Database.Database {
  const end = chain.findIndex((m) => m.id === through)
  if (end < 0) throw new Error(`no migration ${through}`)
  const d = new Database(':memory:')
  d.pragma('foreign_keys = ON')
  for (const m of chain.slice(0, end + 1)) d.transaction(() => d.exec(m.sql))()
  return d
}

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`

/** The schema and seed rows of a chain-built database, as SQL that rebuilds it. */
export function generateBaseline(chain: readonly Migration[], through: string): string {
  const d = chainDb(chain, through)
  try {
    // SQLite keeps each object's current CREATE text, columns added or dropped by ALTER
    // TABLE included and in physical order, so a table rebuilt from it has the same shape.
    const objects = d
      .prepare(
        `SELECT type, name, sql FROM sqlite_master
          WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
          ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name`,
      )
      .all() as { type: string; name: string; sql: string }[]
    const out = objects.map((o) => `${o.sql};`)
    for (const o of objects.filter((x) => x.type === 'table')) {
      const rows = d.prepare(`SELECT * FROM "${o.name}" ORDER BY rowid`).all() as Record<string, unknown>[]
      for (const r of rows) {
        const cols = Object.keys(r)
        const values = cols.map((c) => {
          const v = r[c]
          if (v === null) return 'NULL'
          if (typeof v === 'number' || typeof v === 'bigint') return String(v)
          return quote(String(v))
        })
        out.push(`INSERT INTO "${o.name}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${values.join(', ')});`)
      }
    }
    return out.join('\n')
  } finally {
    d.close()
  }
}

/** The text of src/db/schema.ts for that SQL. */
export function renderSchemaModule(sql: string, through: string): string {
  const body = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
  return [
    '// Generated by `npm run db:baseline` from src/db/legacy.ts. Do not edit.',
    `export const BASELINE_THROUGH = '${through}'`,
    `export const BASELINE_SQL = \`${body}\``,
    '',
  ].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const id = MIGRATIONS.at(-1)!.id
  writeFileSync(fileURLToPath(new URL('./schema.ts', import.meta.url)), renderSchemaModule(generateBaseline(MIGRATIONS, id), id))
  console.log(`wrote src/db/schema.ts through ${id}`)
}
